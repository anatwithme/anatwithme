create or replace function public.prevent_profile_protected_updates()
returns trigger
language plpgsql
security definer
set search_path to 'public'
as $$
begin
  -- Only owners can change roles
  if new.role is distinct from old.role
     and not public.is_owner() then
    raise exception 'Only owners may change roles';
  end if;

  -- Nobody can change user IDs
  if new.user_id is distinct from old.user_id then
    raise exception 'Not allowed to update user_id';
  end if;

  -- Nobody manually changes email
  if new.email is distinct from old.email then
    raise exception 'Not allowed to update email';
  end if;

  return new;
end;
$$;

-- Allows owners to promote students to admins or demote admins to students.
create or replace function public.set_user_role(
  target_user uuid,
  new_role public.role
)
returns void
language plpgsql
security definer
set search_path to 'public'
as $$
declare
  target_role public.role;
begin
  -- Only owners may change roles
  if not public.is_owner() then
    raise exception 'Owner only';
  end if;

  -- Verify target exists and get current role
  select role
  into target_role
  from public.profile
  where user_id = target_user;

  if target_role is null then
    raise exception 'User not found';
  end if;

  -- Prevent owners from demoting themselves
  if target_user = auth.uid() then
    raise exception 'Cannot change your own role';
  end if;

  update public.profile
  set role = new_role
  where user_id = target_user;
end;
$$;

create or replace function public.shares_group_with(target_user uuid)
returns boolean
language sql
security definer
set search_path to 'public'
as $$
  select exists (
    select 1
    from public.member_of m1
    join public.member_of m2 on m1.group_id = m2.group_id
    where m1.user_id = (select auth.uid())
      and m2.user_id = target_user
  );
$$;

create or replace function public.can_view_task_completion(target_user_id uuid)
returns boolean
language sql
security definer
set search_path to 'public'
as $$
  select
    target_user_id = (select auth.uid())
    or public.is_admin()
    or exists (
      select 1
      from public.member_of me
      join public.member_of other on me.group_id = other.group_id
      where me.user_id = (select auth.uid())
        and other.user_id = target_user_id
    );
$$;

create or replace function public.get_my_group_members()
returns table (
  user_id uuid,
  full_name text,
  email text,
  phone text,
  profile_picture_url text,
  bio text
)
language sql
security definer
set search_path to 'public'
as $$
  select p.user_id, p.full_name, p.email, p.phone, p.profile_picture_url, p.bio
  from public.member_of mo
  join public.profile p on p.user_id = mo.user_id
  where mo.group_id in (
    select group_id from public.member_of where user_id = (select auth.uid())
  );
$$;


-- Handles copying of agendas and their sections and tasks
create or replace function public.copy_agenda(source_agenda_id integer)
returns integer
language plpgsql
security definer
set search_path to 'public'
as $$
declare
  new_agenda_id integer;
  source_week integer;
  source_section record;
  new_section_id integer;
begin
  if not public.is_admin() then
    raise exception 'Admin only';
  end if;

  select week
  into source_week
  from public.agenda
  where id = source_agenda_id;

  if source_week is null then
    raise exception 'Cannot copy agenda without a week';
  end if;

  -- Temporarily move rows below the copied agenda
  update public.agenda
  set week = -week
  where week > source_week;

  -- Move them down one
  update public.agenda
  set week = abs(week) + 1
  where week < 0;

  insert into public.agenda (
    title,
    description,
    week,
    start_date,
    end_date,
    enabled
  )
  select
    title || ' Copy',
    description,
    source_week + 1,
    start_date,
    end_date,
    false
  from public.agenda
  where id = source_agenda_id
  returning id into new_agenda_id;

  for source_section in
    select *
    from public.section
    where agenda_id = source_agenda_id
    order by "order"
  loop
    insert into public.section (
      agenda_id,
      title,
      description,
      type,
      "order"
    )
    values (
      new_agenda_id,
      source_section.title,
      source_section.description,
      source_section.type,
      source_section."order"
    )
    returning id into new_section_id;

    insert into public.task (
      section_id,
      title,
      description,
      link,
      "order"
    )
    select
      new_section_id,
      title,
      description,
      link,
      "order"
    from public.task
    where section_id = source_section.id;
  end loop;

  return new_agenda_id;
end;
$$;

