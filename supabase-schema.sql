drop schema if exists public cascade;
create schema public;

grant usage on schema public to postgres, anon, authenticated, service_role;
grant all on schema public to postgres, service_role;

create extension if not exists pgcrypto with schema public;

create type public.role as enum ('student', 'admin', 'owner');
create type public.section_type as enum ('solo', 'group');

create table public.profile (
  user_id uuid primary key references auth.users(id) on delete cascade,
  full_name text,
  role public.role not null default 'student',
  email text,
  phone text,
  profile_picture_url text,
  preference text default 'no_preference',
  bio text,
  study_mode text not null default 'group',

  constraint profile_phone_digits_check check (phone is null or phone ~ '^[0-9]{10}$'),
  constraint profile_preference_check check (preference is null or preference in ('in_person', 'online', 'no_preference')),
  constraint profile_bio_length_check check (bio is null or char_length(bio) <= 500),
  constraint profile_study_mode_check check (study_mode in ('group', 'independent'))
);

create table public.agenda (
  id bigint generated by default as identity primary key,
  title text not null,
  description text,
  week integer not null unique,
  start_date date not null,
  end_date date not null,
  enabled boolean not null default true
);

create table public.section (
  id bigint generated by default as identity primary key,
  agenda_id bigint not null references public.agenda(id) on delete cascade,
  title text not null,
  description text,
  type public.section_type not null,
  "order" integer,
  unique (agenda_id, "order")
);

create table public.task (
  id bigint generated by default as identity primary key,
  section_id bigint not null references public.section(id) on delete cascade,
  title text not null,
  description text,
  link text,
  "order" integer,
  unique (section_id, "order")
);

-- ============================================================
-- time_slot table
-- Static lookup table - every 1hr block from 7am-11pm, Mon-Sun
-- 16 slots/day x 7 days = 112 rows total
-- Seeded once on setup, never written to by the app
-- ============================================================

create table if not exists public.time_slot (
  id          serial primary key,
  day         int not null check (day between 0 and 6),   -- 0=Mon, 6=Sun
  start_time  time not null,
  end_time    time not null,
  slot_index  int not null unique                          -- (day * 16) + position in day, used by matching algorithm
);

-- Seed all 112 slots (7am-11pm, 1hr blocks, Mon-Sun)
-- Safe to re-run - skips if table already has data
do $$
declare
  d int;
  s int;
  start_t time;
  end_t   time;
  base    time := '07:00:00';  -- grid starts at 7am
begin
  if (select count(*) from public.time_slot) = 0 then
    for d in 0..6 loop
      for s in 0..15 loop  -- 16 slots per day (7am to 11pm)
        start_t := base + (s * interval '1 hour');
        end_t   := start_t + interval '1 hour';
        insert into public.time_slot (day, start_time, end_time, slot_index)
        values (d, start_t, end_t, (d * 16) + s);
      end loop;
    end loop;
  end if;
end $$;

